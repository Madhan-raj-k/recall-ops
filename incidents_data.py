def seed_incidents() -> list[Incident]:
    now = utcnow()
    return [
        Incident(
            incident_id=r["id"],
            title=r["title"],
            service=r["svc"],
            severity=r["sev"],
            occurred_at=(now - timedelta(days=r["days"])).replace(microsecond=0),
            symptoms=r["symptoms"],
            root_cause=r["cause"],
            what_worked=r["worked"],
            what_failed=r["failed"],
            teams=r["teams"],
            runbook=r["runbook"],
            time_to_resolve_min=r["ttr"],
            synthetic=True,
        )
        for r in _RAW
    ]


